import { redirect } from "next/navigation";
import { getSessionUser } from "@/lib/session";
import { peutAccederModule, accueilParRole } from "@/lib/authz";

// Espace Direction : supervision et statistiques agrégées.
export default async function SupervisionLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  const user = await getSessionUser();
  if (!user) redirect("/login");
  if (!peutAccederModule(user, "supervision")) redirect(accueilParRole(user));
  return <>{children}</>;
}
